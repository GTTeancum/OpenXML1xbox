#include "engine/actors/raven_actor_scale_clearance.h"
#include <array>
#include <cmath>
#include <cstdio>
#include <vector>
struct Fixture {
    int scenario=0,queries=0;
    std::array<float,3> position{100,200,300},lower{-10,-15,0},upper{10,15,60};
    std::vector<std::array<float,3>> directions;
    unsigned bounds_calls=0,moves=0;
};
static int sweep(void *context,const float origin[3],const float direction[3],float result[3]) {
    auto &f=*static_cast<Fixture*>(context);int q=f.queries++;
    bool hit=(f.scenario==3&&q==0)||(f.scenario==4&&(q==1||q==2))||(f.scenario==5&&q==1);
    f.directions.push_back({direction[0],direction[1],direction[2]});
    for(int i=0;i<3;++i)result[i]=direction[i]*(hit?0.1f:1.0f);
    return hit;
}
static void bounds(void *context,const float lower[3],const float upper[3]) {
    auto &f=*static_cast<Fixture*>(context);++f.bounds_calls;
    for(int i=0;i<3;++i){f.lower[i]=lower[i];f.upper[i]=upper[i];}
}
static void position(void *context,const float value[3]) {
    auto &f=*static_cast<Fixture*>(context);++f.moves;
    for(int i=0;i<3;++i)f.position[i]=value[i];
}
int main() {
    int failed=0;
    /* Independent expectations captured by xml2-scale-clearance-oracle.py
     * executing retail 2D6D0. These are not generated by the new C algorithm. */
    const int expected_queries[]={0,0,5,1,3,5},expected_bounds[]={0,0,4,0,2,4};
    for(int scenario=0;scenario<6;++scenario) {
        Fixture f;f.scenario=scenario;
        raven_scale_clearance_geometry g={1,scenario==0?0.5f:scenario==1?1.0f:2.0f,
            {20,30,60},{-10,-15,0},{10,15,60},{100,200,300},{{0,1,0},{1,0,0}}};
        raven_scale_clearance_callbacks cb={&f,sweep,bounds,position};
        int result=raven_actor_scale_clearance(&g,&cb);
        bool ok=result==(scenario!=3&&scenario!=4)&&f.queries==expected_queries[scenario]&&
            f.bounds_calls==expected_bounds[scenario]&&f.lower==std::array<float,3>{-10,-15,0}&&
            f.upper==std::array<float,3>{10,15,60}&&f.position[0]==100&&f.position[2]==300&&
            std::fabs(f.position[1]-(scenario==5?191.2f:200.0f))<0.0001f;
        if(f.queries>0)ok=ok&&f.directions[0][2]==61;
        if(f.queries>1)ok=ok&&f.directions[1][1]==22&&f.directions[2][1]==-22;
        if(f.queries>3)ok=ok&&f.directions[3][0]==32&&f.directions[4][0]==-32;
        if(!ok){std::fprintf(stderr,"FAIL scale clearance native vector %d\n",scenario);++failed;}
    }
    if(!failed)std::puts("PASS scale clearance core: 6 independent retail oracle vectors, query directions, repositioning and bounds restoration; guest collision bridge pending");
    return failed?1:0;
}
